#!/usr/bin/env python3
"""Assemble docs/full_system_eval.md from the per-module reports.

    python scripts/full_system_eval.py

Reads the artefacts each phase already produces rather than recomputing, so the
summary cannot drift from the reports it summarises.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DOCS = REPO_ROOT / "docs"


def _table_value(markdown: str, label: str) -> str | None:
    """Pull a value out of a `| label | value |` row."""
    match = re.search(rf"^\|\s*{re.escape(label)}\s*\|\s*([^|]+?)\s*\|", markdown, re.M)
    return match.group(1).strip() if match else None


def main() -> None:
    vein_report = DOCS / "vein_module_eval_report.md"
    risk_report = DOCS / "infection_risk_model_report.md"
    latency_file = DOCS / "latency_benchmark.json"

    lines = [
        "# IntelliCannula — Full System Evaluation",
        "",
        "Generated by `scripts/full_system_eval.py` from the per-module reports.",
        "Do not edit by hand.",
        "",
        "> **Research prototype.** Not a medical device, not clinically "
        "validated, not for patient care. Every output is advisory and requires "
        "clinician confirmation — the system recommends, it never acts.",
        "",
        "## 1 · Pre-cannulation vein module",
        "",
    ]

    if vein_report.exists():
        text = vein_report.read_text()
        lines += [
            "| Metric | Value |",
            "|---|---:|",
            f"| Dice | {_table_value(text, 'Dice') or 'n/a'} |",
            f"| IoU | {_table_value(text, 'IoU') or 'n/a'} |",
            f"| Precision | {_table_value(text, 'Precision') or 'n/a'} |",
            f"| Recall | {_table_value(text, 'Recall') or 'n/a'} |",
            "",
            "Scored on the held-out CUBITAL test split, **subject-level** — no "
            "subject appears in more than one split, so a person's second arm "
            "cannot leak into evaluation.",
            "",
            "**Distance to practitioner-marked insertion points: not computed.** "
            "CUBITAL ships 384 annotated samples, but the marks are drawn *on* "
            "the images rather than stored as coordinates, so a converter is "
            "needed before this metric exists. It is the metric that matters "
            "clinically — agreement with practice, not pixel overlap — and its "
            "absence is the largest gap in this evaluation.",
            "",
            "See [`vein_module_eval_report.md`](vein_module_eval_report.md), "
            "including the documented failure where predictions land on the "
            "bedsheet rather than the arm.",
            "",
        ]
    else:
        lines += ["> Not yet generated — run `python vein_module/src/evaluate.py`.", ""]

    lines += ["## 2 · Cannula detection (YOLOv11)", "",
              "**Not trained.** Requires 100–200 hand-labelled cannula-hub images, "
              "which do not exist publicly. Tooling and labelling guide are in "
              "place: [`labeling_guide.md`](labeling_guide.md). Until then the "
              "infection pipeline falls back to a centre-of-frame ROI, which "
              "assumes the photographer centred the site.", ""]

    lines += ["## 3 · Infection risk model", ""]
    if risk_report.exists():
        text = risk_report.read_text()
        lines += [
            "| Metric (5-fold, grouped by wound) | Value |",
            "|---|---:|",
        ]
        for metric in ("precision", "recall", "f1", "auc", "avg_precision"):
            lines.append(f"| {metric} | {_table_value(text, metric) or 'n/a'} |")
        lines += [
            "",
            "**These are proxy-label numbers and must always be quoted as such.** "
            "No public dataset labels a wound as infected, so the target is "
            "wound tissue (1) versus intact skin (0). A feature ablation in the "
            "full report shows four colour-variance features alone reach the "
            "same F1 as all thirty: the model separates classes by *visual "
            "heterogeneity*, not by erythema. Early phlebitis is the opposite "
            "profile — uniformly slightly red intact skin — so this score does "
            "not evidence clinical capability.",
            "",
            "External check on 21 IV-relevant Medetec images (extravasation "
            "injuries): **100% detection**, mean risk 0.993. Every image there "
            "is abnormal, so this is recall with no negative class — and those "
            "injuries are severe, established damage rather than the early "
            "signal the system targets.",
            "",
            "See [`infection_risk_model_report.md`](infection_risk_model_report.md).",
            "",
        ]
    else:
        lines += ["> Not yet generated.", ""]

    lines += ["## 4 · Temporal validation", "",
              "No public longitudinal IV-site dataset exists — no dataset "
              "photographs the same site on consecutive days. The alert "
              "thresholds (risk > 0.6, delta > 0.15, three consecutive "
              "increases) are the values specified in the project plan, **never "
              "fitted to outcome data**. Their false-alarm and missed-detection "
              "rates are unmeasured.", ""]

    lines += ["## 5 · End-to-end latency", ""]
    if latency_file.exists():
        results = json.loads(latency_file.read_text())
        lines += ["| Pipeline | Device | Runs | Mean | p95 |", "|---|---|---:|---:|---:|"]
        for r in results:
            lines.append(
                f"| {r['pipeline']} | {r['device']} | {r['runs']} | "
                f"{r['mean_ms']:.0f} ms | {r['p95_ms']:.0f} ms |"
            )
        lines += [
            "",
            "Image-in to result-out, not just the forward pass. Both are well "
            "inside what a bedside interaction tolerates.",
            "",
        ]
    else:
        lines += ["> Run `python scripts/benchmark_latency.py`.", ""]

    lines += [
        "## Limitations",
        "",
        "1. **NIR training, RGB deployment.** The vein model is trained on "
        "near-infrared imagery because every public vein dataset with masks is "
        "NIR. Deploying against an ordinary RGB camera is an unmeasured domain "
        "shift, and no public RGB vein dataset with masks exists to measure it.",
        "",
        "2. **Paediatric training cohort.** CUBITAL is 1,008 subjects aged 5–22 "
        "(median 11), 97% recorded as slim, 42 obese. The clinical need is in "
        "elderly, obese and dehydrated adults, where veins are hardest to find. "
        "Transfer to that population is untested and must not be assumed.",
        "",
        "3. **Proxy infection labels.** No dataset labels an IV site as "
        "infected. The risk model learns wound-versus-skin, and the ablation "
        "shows it keys on heterogeneity rather than redness.",
        "",
        "4. **No cannula-detection data.** Phase 4 is scaffolding only.",
        "",
        "5. **No longitudinal data.** The temporal tracker's thresholds are "
        "unvalidated.",
        "",
        "6. **Under-trained vein model.** The current checkpoint is epoch 6 of a "
        "planned 25, stopped when the machine exhausted swap. Validation Dice "
        "was still climbing, so the reported figures are a lower bound.",
        "",
        "7. **Known failure mode.** The vein model produces predictions on "
        "background linen, and can place an insertion marker off the patient. "
        "The fix — using CUBITAL's arm class, which the loader currently "
        "discards — is identified but not yet implemented.",
        "",
        "## What would make this clinically credible",
        "",
        "- An IRB-approved prospective collection of IV sites photographed daily, "
        "with clinician-assessed phlebitis grading. That single dataset would "
        "replace the proxy labels, provide real longitudinal validation, and "
        "supply the cannula-detection images.",
        "- An adult cohort for the vein module, spanning body habitus and skin tone.",
        "- A formal validation study before any clinical use.",
        "",
    ]

    out = DOCS / "full_system_eval.md"
    out.write_text("\n".join(lines))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
